import type { Metadata } from "next";
import { siteConfig } from "@/lib/config";

// Small helpers for turning editable page content into <meta> values and
// structured data.

// Collapse whitespace and clip to a length that reads well in search
// results / social cards (~160 chars for descriptions), breaking on a word
// boundary and adding an ellipsis when clipped.
export function metaDescription(text: string, max = 160): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const clipped = clean.slice(0, max);
  const lastSpace = clipped.lastIndexOf(" ");
  return `${clipped.slice(0, lastSpace > 0 ? lastSpace : max).trimEnd()}…`;
}

// Branded 1200×630 card generated by app/og/route.tsx — the share image for
// any page that has no photo of its own.
export const defaultShareImage = {
  url: "/og",
  width: 1200,
  height: 630,
  alt: siteConfig.name,
};

// Uploaded originals are stored full size (14MB+ PNGs happen), past the 8MB
// Facebook / 5MB X limits for share images. Route them through the Next
// image optimizer at 1200px wide instead of linking the raw upload. q must
// be in images.qualities (Next only allows 75 unless configured).
export function shareImage(src: string, alt: string) {
  return {
    url: `/_next/image?url=${encodeURIComponent(src)}&w=1200&q=75`,
    alt,
  };
}

// Full metadata for a site page. Next merges metadata shallowly, so a page
// that sets `openGraph` or `twitter` replaces the root layout's version
// wholesale — this rebuilds every field each time so no page loses the site
// name, locale or share image, and the X card always matches the page.
export function pageMetadata({
  title,
  description,
  path,
  image,
  type = "website",
}: {
  // Shown in the tab as "Title — OUTOFSIGHT"; null means just the brand name.
  title: string | null;
  description: string;
  path: string;
  image?: { url: string; alt: string } | null;
  type?: "website" | "article";
}): Metadata {
  const fullTitle = title ? `${title} — ${siteConfig.name}` : siteConfig.name;
  const images = [image ?? defaultShareImage];
  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: path },
    openGraph: {
      type,
      siteName: siteConfig.name,
      locale: "en_US",
      url: path,
      title: fullTitle,
      description,
      images,
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: images.map((i) => i.url),
    },
  };
}

// Absolute URL for structured data (JSON-LD has no metadataBase).
export function absoluteUrl(path: string) {
  return new URL(path, siteConfig.url).toString();
}

// JSON for a <script type="application/ld+json">. Escapes "<" so admin-edited
// text containing "</script>" can't break out of the tag.
export function jsonLd(data: unknown) {
  return { __html: JSON.stringify(data).replace(/</g, "\\u003c") };
}
